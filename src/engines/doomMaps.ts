/** Hand-crafted Doom-style maze layouts. # wall, . floor, S spawn, D door (opens as floor after kill quota). */

export function getDoomMap(level: number): string[] {
  const hand: string[][] = [
    [
      '####################',
      '#S.................#',
      '#.######.....#######',
      '#......#.....#......',
      '#.####.#.....#.####.',
      '#......#.....#......',
      '#.########...######.',
      '#..................#',
      '####################',
    ],
    [
      '######################',
      '#S...................#',
      '#######.########.#####',
      '#.......#......#.....#',
      '#.#####.#.####.#.###.#',
      '#.....#.#....#.#...#.#',
      '###.#.#.####.#.###.#.#',
      '#...#.#......#.....#.#',
      '#.###.########.#####.#',
      '#....................#',
      '######################',
    ],
    [
      '########################',
      '#S.......#.............#',
      '#.######.#.###########.#',
      '#.#....#.#.#.........#.#',
      '#.#.##.#.#.#.#######.#.#',
      '#.#.#..#...#.#.....#.#.#',
      '#.#.#.####.#.#.###.#.#.#',
      '#...#......#.#...#.#...#',
      '#####.######.#.###.#####',
      '#......................#',
      '########################',
    ],
  ];
  if (level <= hand.length) return hand[level - 1];
  return generateDoomMap(20 + level * 2, level);
}

function generateDoomMap(size: number, seed: number): string[] {
  const rows: string[] = [];
  for (let y = 0; y < size; y++) {
    let row = '';
    for (let x = 0; x < size; x++) {
      if (x === 0 || y === 0 || x === size - 1 || y === size - 1) row += '#';
      else if (x === 2 && y === 2) row += 'S';
      else if ((x * 7 + y * 13 + seed) % 11 === 0 && x > 3 && y > 3 && x < size - 4 && y < size - 4) row += '#';
      else row += '.';
    }
    rows.push(row);
  }
  return rows;
}
